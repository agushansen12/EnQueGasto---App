-- EnQuéGasto: catálogo inicial de conocimiento del asistente
-- Seguro para ejecutar más de una vez: no modifica movimientos ni categorías existentes.

create table if not exists public.assistant_knowledge (
  id uuid primary key default gen_random_uuid(),
  household_id uuid null references public.households(id) on delete cascade,
  phrase text not null,
  normalized_phrase text not null,
  movement_type text not null check (movement_type in ('expense', 'income')),
  category_name text not null,
  canonical_concept text not null,
  match_type text not null default 'phrase' check (match_type in ('phrase', 'merchant')),
  priority integer not null default 70,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint assistant_knowledge_phrase_not_empty check (length(trim(phrase)) > 0),
  constraint assistant_knowledge_normalized_not_empty check (length(trim(normalized_phrase)) > 0)
);

create unique index if not exists assistant_knowledge_global_unique
  on public.assistant_knowledge (normalized_phrase, movement_type)
  where household_id is null;

create unique index if not exists assistant_knowledge_household_unique
  on public.assistant_knowledge (household_id, normalized_phrase, movement_type)
  where household_id is not null;

create index if not exists assistant_knowledge_lookup_idx
  on public.assistant_knowledge (movement_type, is_active, priority desc);

alter table public.assistant_knowledge enable row level security;

drop policy if exists "Authenticated users can read global and household assistant knowledge" on public.assistant_knowledge;
create policy "Authenticated users can read global and household assistant knowledge"
  on public.assistant_knowledge for select to authenticated
  using (household_id is null or public.is_household_member(household_id));

drop policy if exists "Household members can add their own assistant knowledge" on public.assistant_knowledge;
create policy "Household members can add their own assistant knowledge"
  on public.assistant_knowledge for insert to authenticated
  with check (household_id is not null and public.is_household_member(household_id));

drop policy if exists "Household members can update their own assistant knowledge" on public.assistant_knowledge;
create policy "Household members can update their own assistant knowledge"
  on public.assistant_knowledge for update to authenticated
  using (household_id is not null and public.is_household_member(household_id))
  with check (household_id is not null and public.is_household_member(household_id));

drop policy if exists "Household members can delete their own assistant knowledge" on public.assistant_knowledge;
create policy "Household members can delete their own assistant knowledge"
  on public.assistant_knowledge for delete to authenticated
  using (household_id is not null and public.is_household_member(household_id));

revoke all on table public.assistant_knowledge from public, anon;
grant select, insert, update, delete on table public.assistant_knowledge to authenticated;

